#!/usr/bin/env python3
"""Run local detections on synthetic evaluation data or real LogHub events."""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import time
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from cybersecurity.detection_engine import (  # noqa: E402
    DetectionConfig,
    build_baseline,
    detect,
)
from cybersecurity.evaluation import evaluate_scenarios  # noqa: E402


DATASETS = ("OpenSSH", "Linux", "Apache")


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, start=1):
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError as error:
                raise ValueError(
                    f"Malformed JSONL at {path.relative_to(ROOT)}:{line_number}"
                ) from error
    return records


def write_jsonl(path: Path, rows: list[dict[str, Any]], force: bool) -> None:
    if path.exists() and not force:
        raise FileExistsError(
            f"{path.relative_to(ROOT)} exists; use --force to replace it"
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            prefix=f".{path.name}.",
            suffix=".tmp",
            dir=path.parent,
            delete=False,
        ) as stream:
            temporary_path = Path(stream.name)
            for row in rows:
                stream.write(json.dumps(row, ensure_ascii=False) + "\n")
        os.replace(temporary_path, path)
        temporary_path = None
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def load_config(path: Path | None) -> DetectionConfig:
    if path is None:
        return DetectionConfig()
    with path.open("r", encoding="utf-8") as stream:
        values = json.load(stream)
    if not isinstance(values, dict):
        raise ValueError("detection config JSON must contain an object")
    return DetectionConfig.from_mapping(values)


def load_annotations(path: Path) -> list[dict[str, str]]:
    return load_jsonl(path)


def render_evaluation_report(
    metrics: dict[str, Any],
    alert_counts: Counter[tuple[str, str]],
    config: DetectionConfig,
    detection_seconds: float,
    malformed_events: int,
) -> str:
    rows = [
        ["TP", str(metrics["tp"])],
        ["TN", str(metrics["tn"])],
        ["FP", str(metrics["fp"])],
        ["FN", str(metrics["fn"])],
    ]
    rule_rows = [
        [rule_id, category, str(count)]
        for (rule_id, category), count in sorted(alert_counts.items())
    ] or [["—", "No alerts", "0"]]
    return "\n".join(
        [
            "# Synthetic Detection Evaluation",
            "",
            "Generated by `scripts/run_detection.py` from local synthetic data. "
            "Scenario labels are loaded from a separate annotation file only "
            "after detection completes.",
            "",
            "## Evaluation method",
            "",
            f"- Unit: **scenario-level** ({metrics['scenario_count']} evaluation scenarios).",
            "- A scenario is predicted suspicious if at least one security alert "
            "references an event assigned to that scenario. Operational-anomaly "
            "alerts are excluded from security metrics.",
            "- Detector inputs contain normalized events only; scenario IDs and "
            "ground-truth labels are held in a separate annotation JSONL.",
            "- Development events build the R06 baseline and are not included in "
            "evaluation metrics.",
            "",
            "## Results",
            "",
            f"- Suspicious scenarios: {metrics['suspicious_scenarios']}",
            f"- Benign scenarios: {metrics['benign_scenarios']}",
            f"- Precision: {metrics['precision']:.4f}",
            f"- Recall: {metrics['recall']:.4f}",
            f"- F1-score: {metrics['f1']:.4f}",
            f"- False-positive rate: {metrics['false_positive_rate']:.4f}",
            f"- Detection execution time: {detection_seconds:.6f} seconds",
            f"- Malformed input events skipped: {malformed_events}",
            f"- Operational anomaly alerts excluded: "
            f"{metrics['operational_anomaly_alerts_excluded']}",
            "",
            "### Confusion matrix",
            "",
            markdown_table(["Actual / predicted", "Count"], rows),
            "",
            "### Alerts by rule and category",
            "",
            markdown_table(["Rule", "Category", "Alerts"], rule_rows),
            "",
            "## Interpretation",
            "",
            "These deterministic results describe this generated scenario set "
            "and its documented thresholds only. They are not estimates of "
            "real-world attack-detection accuracy.",
            "",
        ]
    )


def markdown_table(headers: list[str], rows: list[list[str]]) -> str:
    return "\n".join(
        [
            "| " + " | ".join(headers) + " |",
            "| " + " | ".join("---" for _ in headers) + " |",
            *("| " + " | ".join(row) + " |" for row in rows),
        ]
    )


def run_synthetic(config: DetectionConfig, force: bool) -> int:
    synthetic = ROOT / "data" / "synthetic"
    dev_path = synthetic / "development_events.jsonl"
    eval_path = synthetic / "evaluation_events.jsonl"
    output_path = ROOT / "data" / "processed" / "synthetic_alerts.jsonl"
    report_path = ROOT / "docs" / "DETECTION_EVALUATION.md"
    for path in (output_path, report_path):
        if path.exists() and not force:
            raise FileExistsError(
                f"{path.relative_to(ROOT)} exists; use --force to replace"
            )

    development = load_jsonl(dev_path)
    evaluation = load_jsonl(eval_path)
    baseline = build_baseline(development, config)
    started = time.perf_counter()
    result = detect(evaluation, config, baseline)
    detection_seconds = time.perf_counter() - started

    annotations = load_annotations(synthetic / "evaluation_annotations.jsonl")
    metrics = evaluate_scenarios(annotations, result.alerts)
    write_jsonl(output_path, result.alerts, force=force)
    alert_counts = Counter(
        (alert["rule_id"], alert["category"]) for alert in result.alerts
    )
    report_path.write_text(
        render_evaluation_report(
            metrics,
            alert_counts,
            config,
            detection_seconds,
            result.malformed_event_count,
        ),
        encoding="utf-8",
        newline="\n",
    )
    security_count = sum(alert["category"] == "security" for alert in result.alerts)
    operational_count = sum(
        alert["category"] == "operational_anomaly" for alert in result.alerts
    )
    print(
        f"Synthetic evaluation: {len(evaluation)} events; "
        f"{len(result.alerts)} alerts ({security_count} security, "
        f"{operational_count} operational); "
        f"TP={metrics['tp']} TN={metrics['tn']} FP={metrics['fp']} FN={metrics['fn']}; "
        f"precision={metrics['precision']:.4f} recall={metrics['recall']:.4f} "
        f"F1={metrics['f1']:.4f} FPR={metrics['false_positive_rate']:.4f}; "
        f"detection={detection_seconds:.6f}s"
    )
    print(f"Alert output: {output_path.relative_to(ROOT)}")
    print(f"Evaluation report: {report_path.relative_to(ROOT)}")
    return 0


def run_real_logs(config: DetectionConfig, force: bool) -> int:
    outputs = {
        dataset: ROOT / "data" / "processed" / f"real_{dataset.lower()}_alerts.jsonl"
        for dataset in DATASETS
    }
    existing = [path for path in outputs.values() if path.exists()]
    if existing and not force:
        raise FileExistsError(
            "Real-log alert outputs exist; use --force to replace: "
            + ", ".join(path.relative_to(ROOT).as_posix() for path in existing)
        )

    for dataset, output_path in outputs.items():
        event_path = (
            ROOT / "data" / "processed" / f"{dataset.lower()}_events.jsonl"
        )
        events = load_jsonl(event_path)
        started = time.perf_counter()
        result = detect(events, config, baseline=None)
        elapsed = time.perf_counter() - started
        write_jsonl(output_path, result.alerts, force=force)
        counts = Counter(
            (alert["rule_id"], alert["category"]) for alert in result.alerts
        )
        print(
            f"{dataset}: {len(events)} entries; {len(result.alerts)} rule alerts; "
            f"malformed={result.malformed_event_count}; elapsed={elapsed:.6f}s; "
            f"rule/category counts={dict(sorted(counts.items()))}"
        )
    print(
        "These are rule-matched patterns in unlabeled LogHub data, not confirmed attacks. "
        "R06 was skipped because no comparable labeled development baseline was supplied."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--real-logs", action="store_true")
    mode.add_argument(
        "--synthetic",
        action="store_true",
        help="evaluate the synthetic split (default)",
    )
    parser.add_argument("--config-json", type=Path)
    parser.add_argument("--force", action="store_true")
    arguments = parser.parse_args(argv)
    try:
        config = load_config(arguments.config_json)
        if arguments.real_logs:
            return run_real_logs(config, arguments.force)
        return run_synthetic(config, arguments.force)
    except (OSError, UnicodeError, json.JSONDecodeError, ValueError) as error:
        print(f"Detection run failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
